export function classifyClientTier(proj: Partial<ActiveProjectItem>): ClientTier {
  if (proj.clientTier) return proj.clientTier;
  const name = (proj.name || '').toLowerCase();
  const client = (proj.client || '').toLowerCase();
  const amount = proj.paymentAmountNumeric || 0;

  // Agency partner accounts (Rank Harvest, partner agencies, white-label)
  if (client.includes('rank harvest') || client.includes('agency') || name.includes('white label') || name.includes('partner') || client.includes('partner')) {
    return 'TIER_A_AGENCY';
  }

  // High-Ticket / VIP (International & E-commerce, Enterprise SEO, High Retainer >= $1,500)
  if (
    amount >= 1500 ||
    name.includes('ecommerce') ||
    name.includes('e-commerce') ||
    name.includes('shopify') ||
    name.includes('enterprise') ||
    name.includes('global') ||
    name.includes('robotics') ||
    name.includes('saas') ||
    name.includes('international')
  ) {
    return 'TIER_S_VIP';
  }

  // Local / standard budget accounts
  return 'TIER_B_LOCAL';
}

